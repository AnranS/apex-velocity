/**
 * Regenerates src/audio/engine-calib.ts — level tables for every engine voicing.
 *   npx tsx tools/audio/calibrate.ts
 * Pass 1 measures the raw core RMS (debug mode 1) on the (rpmNorm × load) grid for the rich player voice and the
 * cheap voice; pass 2 measures the RMS after normalisation + soft clip (debug mode 2). The DSP divides by these
 * so that the loudness curve is exact no matter how the timbre is voiced.
 */
import { writeFileSync } from 'node:fs';
import { renderVoice, rms } from './lib';
import { engineConfig, CAL_N, CAL_R0, CAL_R1, NOMINAL_RPM_MAX, type EngineType } from '../../src/audio/engine-configs';

const TYPES: EngineType[] = ['v8', 'v12', 'i6t', 'v10'];
const LOADS = [0, 0.5, 1];
const WARM = 0.45;

function measure(type: EngineType, player: boolean, norm: number, load: number, debug: number, cfg = engineConfig(type)): number {
  const rpmMax = NOMINAL_RPM_MAX[type];
  const rpm = norm * rpmMax;
  const cyc = Math.max(4, rpm / 120);
  const dur = WARM + Math.max(0.6, 10 / cyc);
  const r = renderVoice({ type, player, dur, debug, cfg, state: () => ({ rpm, norm, load, gain: 1, pan: 0 }) });
  const a = Math.round(WARM * r.fs);
  const l = rms(r.eL, a);
  const rr = rms(r.eR, a);
  const v = Math.sqrt((l * l + rr * rr) / 2);
  return player ? v : v / Math.SQRT1_2;
}

function smoothRows(tab: number[]): number[] {
  // 3-point smoothing along rpm in the log domain, per (voice kind, load) column
  const out = tab.slice();
  for (let k = 0; k < 2; k++) {
    for (let j = 0; j < 3; j++) {
      const at = (r: number) => Math.log(tab[k * CAL_N * 3 + Math.min(CAL_N - 1, Math.max(0, r)) * 3 + j]);
      for (let r = 0; r < CAL_N; r++) out[k * CAL_N * 3 + r * 3 + j] = Math.exp(0.25 * at(r - 1) + 0.5 * at(r) + 0.25 * at(r + 1));
    }
  }
  return out;
}

const result: Record<string, { pre: number[]; post: number[] }> = {};
for (const type of TYPES) {
  let pre: number[] = [];
  for (const player of [true, false]) {
    for (let r = 0; r < CAL_N; r++) {
      const norm = CAL_R0 + ((CAL_R1 - CAL_R0) * r) / (CAL_N - 1);
      for (const l of LOADS) pre.push(measure(type, player, norm, l, 1));
    }
  }
  pre = smoothRows(pre);
  const cfg = { ...engineConfig(type), pre, post: new Array<number>(CAL_N * 6).fill(0.2) };
  let post: number[] = [];
  for (const player of [true, false]) {
    for (let r = 0; r < CAL_N; r++) {
      const norm = CAL_R0 + ((CAL_R1 - CAL_R0) * r) / (CAL_N - 1);
      for (const l of LOADS) post.push(measure(type, player, norm, l, 2, cfg));
    }
  }
  post = smoothRows(post);
  result[type] = { pre, post };
  const row = (t: number[], k: number, j: number) => Array.from({ length: CAL_N }, (_, r) => t[k * CAL_N * 3 + r * 3 + j].toFixed(3)).join(' ');
  console.log(`${type}  pre  player load1: ${row(pre, 0, 2)}`);
  console.log(`${type}  pre  player load0: ${row(pre, 0, 0)}`);
  console.log(`${type}  post player load1: ${row(post, 0, 2)}`);
  console.log(`${type}  pre  cheap  load1: ${row(pre, 1, 2)}`);
}

const num = (v: number) => Number(v.toPrecision(5));
let src = '// GENERATED by tools/audio/calibrate.ts — do not edit by hand.\n';
src += '// Level tables per engine: rows = rpmNorm grid (player voice rows first, then cheap-voice rows), 3 load columns.\n';
src += 'export const ENGINE_CALIB: Record<string, { pre: number[]; post: number[] }> = {\n';
for (const type of TYPES) {
  src += `  ${type}: {\n    pre: [${result[type].pre.map(num).join(', ')}],\n    post: [${result[type].post.map(num).join(', ')}],\n  },\n`;
}
src += '};\n';
writeFileSync(new URL('../../src/audio/engine-calib.ts', import.meta.url), src);
console.log('wrote src/audio/engine-calib.ts');
